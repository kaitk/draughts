# The light from outside the library's windows by direction, for the app's bake
# (model3d::outside_light): Cycles' panorama of the outside (scene.py --pano from just past the
# middle window, with --sky and --view-out pictures) averaged into 5° cells by azimuth and
# elevation, over the luminance of the sun's light in the same render, and the sun itself.
#
#   python3 tools/blender/outside_table.py PANO-combined.npy SKY.json SCENE.json NAME OUT.goose   (then goose format OUT)
#
# SKY.json is sky_model.py's, SCENE.json the export's (its sun's light sets the units, as
# scene.py's --sky does). The panorama's middle looks along the plan's +y (out), u 0.75 along
# the plan's +x, so a cell's azimuth is atan2(v.x, v.y) of the plan's direction v outward.
import json
import sys

import numpy as np

AZ0, AZ_STEP, COLS = -85.0, 5.0, 34      # azimuths -85 to 85 degrees from straight out
EL0, EL_STEP, ROWS = -30.0, 5.0, 24      # elevations -30 to 90 degrees


def lum(c):
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


pano, sky_json, scene_json, name, out = sys.argv[1:6]
c = np.load(pano)[..., :3].astype(np.float64)
H, W = c.shape[:2]
lat = 90 - (np.arange(H) + 0.5) * 180 / H
lon = (np.arange(W) + 0.5) * 360 / W - 180
M = json.load(open(sky_json))
S = json.load(open(scene_json))
units = lum(S["sun_irradiance"]) / 0.25 / lum(M["clear_sun"])   # scene.py's --sky, --sun-take 0.25
sun = np.array(M["sun"]) * units
clear = lum(S["sun_irradiance"]) / 0.25
w = np.cos(np.radians(lat))[:, None] * np.ones((1, W))
cells = []
for j in range(ROWS):
    e0 = EL0 + j * EL_STEP
    rows = (lat >= e0) & (lat < e0 + EL_STEP)
    for i in range(COLS):
        a0 = AZ0 + i * AZ_STEP
        cols = (lon >= a0) & (lon < a0 + AZ_STEP)
        m = rows[:, None] & cols[None, :]
        v = (c[m] * w[m][:, None]).sum(0) / w[m].sum()
        cells.append(v / lum(sun))
lines = [
    "// Generated by tools/blender/outside_table.py from Cycles' panorama of the outside; don't edit.",
    "namespace outside_light;",
    "",
    "let OUTSIDE_COLS = %d;" % COLS,
    "let OUTSIDE_ROWS = %d;" % ROWS,
    "let OUTSIDE_AZ0: f32 = %.1f;" % AZ0,
    "let OUTSIDE_EL0: f32 = %.1f;" % EL0,
    "let OUTSIDE_STEP: f32 = %.1f;" % AZ_STEP,
    "",
    "// %s: the sun's light over the clear sun's luminance (rgb), and the outside's radiance by" % name,
    "// direction over the sun's luminance, OUTSIDE_COLS azimuths from OUTSIDE_AZ0 by OUTSIDE_STEP",
    "// degrees, OUTSIDE_ROWS elevations from OUTSIDE_EL0, row by row from the lowest.",
    "let %s_SUN = float3 { %.5f, %.5f, %.5f };" % ((name.upper(),) + tuple(sun / clear)),
    "let %s_OUTSIDE: float3[%d] = [" % (name.upper(), len(cells)),
]
for k in range(0, len(cells), 4):
    lines.append("    " + " ".join("float3 { %.5g, %.5g, %.5g }," % tuple(v) for v in cells[k:k + 4]))
lines.append("];")
open(out, "w").write("\n".join(lines) + "\n")
print("sun over the clear sun", sun / clear, "cells", len(cells), "brightest", max(lum(v) for v in cells))
