#!/usr/bin/env python3
"""Write strings/keys.goose, the string keys and their constants, from strings/en.txt.

    scripts/strings_keys.py          write strings/keys.goose
    scripts/strings_keys.py --check  exit 1 if it isn't what en.txt makes (scripts/test.sh)

Each `key = text` line of en.txt, in the file's order, is an entry of strings::KEYS and
a constant indexing it, the key uppercased with its dots as underscores (home.continue is
HOME_CONTINUE); COUNT is how many. The `#` lines right above a key, with no blank line
between, become the constant's comment. Code that steps through keys by offset
(MARK_ONLY + 2 * mark, HOW_STEP + 3 * step) relies on en.txt keeping such a run together
and in order; test/strings checks each run.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EN = ROOT / "strings/en.txt"
OUT = ROOT / "strings/keys.goose"


def generate(text):
    keys, notes, comment = [], {}, []
    for line in text.splitlines():
        l = line.strip()
        if l.startswith("#"):
            comment.append(l[1:].strip())
            continue
        if "=" in l:
            key = l.split("=", 1)[0].strip()
            if comment:
                notes[key] = comment
            keys.append(key)
        comment = []
    out = ["// Generated by scripts/strings_keys.py from strings/en.txt, in its order: edit",
           "// en.txt and run the script, never this file.",
           "namespace strings;",
           "",
           "// The keys, as the files name them; the constants below index KEYS.",
           "let KEYS = ["]
    out += [f'    "{k}",' for k in keys]
    out += ["];", ""]
    for i, k in enumerate(keys):
        out += [f"// {c}".rstrip() for c in notes.get(k, [])]
        out.append(f"let {k.upper().replace('.', '_')} = {i};")
    out.append(f"let COUNT = {len(keys)};")
    return "\n".join(out) + "\n"


def main():
    want = generate(EN.read_text(encoding="utf-8"))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != want:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run scripts/strings_keys.py")
        return
    OUT.write_text(want, encoding="utf-8")


if __name__ == "__main__":
    main()
